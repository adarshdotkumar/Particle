/* Turns a model exported from Blender into a built-in shape.
 *
 * Shared by the command line (scripts/import-model.mjs) and the editor's
 * "Save as shape" button, which posts the uploaded file to the dev server
 * (see vite.config.js). Both end up here.
 *
 * Reads a .glb (or a .gltf) with the same reader the engine uses at runtime
 * (src/engine/gltf.js), merges every mesh in its scene with each node's
 * transform applied, centres it and scales it to 1.0 wide, and writes the
 * result as plain numbers to src/engine/shapes/models/<name>.js. That is the
 * same thing the built-in X is, so the engine still needs no loader and no
 * network for it. Then it regenerates models/index.js and models/catalog.js,
 * which is all it takes for the shape to become a chip in the editor and a
 * valid `shapeMode` in configs.
 *
 * Blender export settings: File → Export → glTF 2.0, format "glTF Binary
 * (.glb)". Leave Compression OFF — Draco/meshopt are not supported here.
 * Materials, textures and animation are ignored; only geometry seeds dots.
 */
import { readFile, writeFile, readdir, unlink } from 'node:fs/promises';
import { basename, extname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { normalizeMeshArrays } from '../../src/engine/shapes/mesh-sample.js';
import { parseGltf, GltfError } from '../../src/engine/gltf.js';

export const MODELS_DIR = fileURLToPath(new URL('../../src/engine/shapes/models/', import.meta.url));

const GENERATED = new Set(['index.js', 'catalog.js']);
// Every other shape mode, plus the old name for the X and the X itself, so an
// import can never shadow a shape that already means something.
const RESERVED = new Set(['sphere', 'cube', 'text', 'custom', 'model', 'x']);
const TRIANGLE_WARN = 20000;

/** A problem with the input the person can fix — shown to them as-is. */
export class ModelImportError extends Error {}
const fail = (message) => { throw new ModelImportError(message); };

/** Lowercase letters, digits and dashes, starting with a letter. */
export function slugify(text) {
  return String(text).toLowerCase().replace(/\.[a-z0-9]+$/, '')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').replace(/^[^a-z]+/, '');
}

export function validateName(name) {
  if (!/^[a-z][a-z0-9-]{0,39}$/.test(name)) {
    fail(`"${name}" isn't a usable name — lowercase letters, digits and dashes, starting with a letter.`);
  }
  if (RESERVED.has(name)) fail(`"${name}" is already a built-in shape. Pick another name.`);
}

/* ── writing ──────────────────────────────────────────────────────────── */

function numbers(values, digits, perLine) {
  const lines = [];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push('    ' + values.slice(i, i + perLine)
      .map((x) => (digits === null ? String(x) : String(Number(x.toFixed(digits)) || 0)))
      .join(', ') + ',');
  }
  return lines.join('\n');
}

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ')}'`;

/** Convert one model and register it.
 *  @returns {{ name, label, vertices, triangles, kB, warnings: string[] }} */
export async function importModel({
  bytes, baseDir = null, sourceName = 'model.glb', name, label, note = 'Blender', dir = MODELS_DIR,
}) {
  validateName(name);
  let merged;
  try {
    merged = await parseGltf(new Uint8Array(bytes), baseDir
      ? (uri) => readFile(resolve(baseDir, decodeURIComponent(uri)))
      : undefined);
  } catch (error) {
    if (error instanceof GltfError) fail(error.message);
    throw error;
  }
  const { position, meshDepth } = normalizeMeshArrays(merged.position, merged.index);
  const vertices = merged.position.length / 3;
  const triangles = merged.index.length / 3;
  const cleanLabel = String(label || name).trim().slice(0, 40) || name;
  const date = new Date().toISOString().slice(0, 10);

  const source = `/* Generated by scripts/import-model.mjs from ${quote(basename(sourceName))} on ${date}.
 * Re-import to update it; don't edit the numbers by hand.
 * ${vertices} vertices, ${triangles} triangles, normalised to 1.0 wide. */

export const meta = { label: ${quote(cleanLabel)}, note: ${quote(note)} };

export default {
  meshDepth: ${Number(meshDepth.toFixed(5))},
  position: [
${numbers([...position], 5, 12)}
  ],
  normal: [
${numbers([...merged.normal], 4, 12)}
  ],
  index: [
${numbers([...merged.index], null, 24)}
  ],
};
`;
  await writeFile(resolve(dir, `${name}.js`), source);
  await syncModels(dir);

  const warnings = [];
  if (merged.skipped) warnings.push(`Skipped ${merged.skipped} part(s) made of lines or points.`);
  if (triangles > TRIANGLE_WARN) {
    warnings.push(`${triangles.toLocaleString('en')} triangles is heavy — every one ships inside the embed. Blender's Decimate modifier can bring it down to a few thousand.`);
  }
  return { name, label: cleanLabel, vertices, triangles, kB: Math.round(source.length / 1024), warnings };
}

/** Delete an imported model and unregister it. The X can't be removed here. */
export async function removeModel(name, dir = MODELS_DIR) {
  if (GENERATED.has(`${name}.js`) || RESERVED.has(name) || !/^[a-z][a-z0-9-]*$/.test(name)) {
    fail(`"${name}" can't be removed.`);
  }
  try {
    await unlink(resolve(dir, `${name}.js`));
  } catch {
    fail(`There's no imported shape called "${name}".`);
  }
  return syncModels(dir);
}

/** Rebuild index.js (the meshes) and catalog.js (just the names) from
 *  whatever model files are in the directory. x comes first, as the default.
 *  @returns {string[]} the registered names */
export async function syncModels(dir = MODELS_DIR) {
  const names = (await readdir(dir))
    .filter((f) => extname(f) === '.js' && !GENERATED.has(f))
    .map((f) => basename(f, '.js'))
    .sort((a, b) => (a === 'x' ? -1 : b === 'x' ? 1 : a.localeCompare(b)));

  const entries = [];
  for (const name of names) {
    const href = `${pathToFileURL(resolve(dir, `${name}.js`)).href}?t=${Date.now()}`;
    const { meta } = await import(href);
    entries.push({ name, label: meta?.label ?? name, note: meta?.note ?? '' });
  }
  const id = (name) => `model_${name.replace(/-/g, '_')}`;

  await writeFile(resolve(dir, 'index.js'), `/* Generated by scripts/import-model.mjs — every built-in model, keyed by
 * shapeMode. Run \`npm run import-model -- --sync\` after adding or removing
 * a model file instead of editing this by hand. */
import { computeAreaCdf } from '../mesh-sample.js';
${entries.map(({ name }) => `import ${id(name)} from './${name}.js';`).join('\n')}

const withCdf = (mesh) => ({ ...mesh, areaCdf: computeAreaCdf(mesh.position, mesh.index) });

export const MODELS = {
${entries.map(({ name }) => `  ${quote(name)}: withCdf(${id(name)}),`).join('\n')}
};
`);

  await writeFile(resolve(dir, 'catalog.js'), `/* Generated by scripts/import-model.mjs — the built-in model shapes, names
 * only. Plain data with no mesh numbers, so config.js can import it and stay
 * light and Node-safe. */
export const MODEL_SHAPES = [
${entries.map(({ name, label, note }) => `  { mode: ${quote(name)}, label: ${quote(label)}, note: ${quote(note)} },`).join('\n')}
];
`);
  return names;
}
